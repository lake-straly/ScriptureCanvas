export function matchStrongsForWord(word: string, isOldTestament: boolean = false): LexiconEntry | undefined {
  const clean = word.toLowerCase().replace(/[^a-z]/g, '');
  const mapping = KEYWORD_STRONGS_MAP[clean];
  if (!mapping) return undefined;
  
  const strongsId = isOldTestament ? mapping.hebrew : mapping.greek;
  return LEXICON_DATABASE[strongsId];
}

export function searchLexicon(query: string): LexiconEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return Object.values(LEXICON_DATABASE);

  return Object.values(LEXICON_DATABASE).filter((entry) => 
    entry.strongs.toLowerCase().includes(q) ||
    entry.original.toLowerCase().includes(q) ||
    entry.transliteration.toLowerCase().includes(q) ||
    entry.shortDef.toLowerCase().includes(q) ||
    entry.definition.toLowerCase().includes(q) ||
    entry.language.toLowerCase().includes(q)
  );
}
